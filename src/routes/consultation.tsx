import { createFileRoute, Link } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";
import { useServerFn } from "@tanstack/react-start";
import {
  MessageCircleHeart,
  Send,
  RotateCcw,
  FileText,
  Copy,
  Download,
  Save,
  Trash2,
  AlertTriangle,
  Phone,
  ShieldCheck,
  Lock,
  CheckCircle2,
  Loader2,
  Stethoscope,
  ChevronRight,
} from "lucide-react";
import { useTranslation } from "react-i18next";
import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/lib/auth";
import { SiteHeader } from "@/components/SiteHeader";
import { SiteFooter } from "@/components/SiteFooter";
import { Button } from "@/components/ui/button";
import { Checkbox } from "@/components/ui/checkbox";
import {
  consultationTurn,
  consultationReport,
  type ConsultMessage,
  type ConsultReport,
  type ConsultStage,
} from "@/lib/consultation.functions";

export const Route = createFileRoute("/consultation")({
  head: () => ({
    meta: [
      { title: "DoseAI — Knowdose" },
      {
        name: "description",
        content:
          "Chat with DoseAI about your symptoms. Get a clear, friendly consultation report with possible explanations and next steps. Not a diagnosis.",
      },
      { property: "og:title", content: "DoseAI — Knowdose" },
      {
        property: "og:description",
        content: "A friendly AI health consultation that helps you understand your symptoms and what to do next.",
      },
      { name: "robots", content: "noindex" },
    ],
  }),
  component: ConsultationPage,
});

const OPENING_MESSAGE =
  "Hi, I'm DoseAI — a health information assistant. I can help you understand your symptoms, but I'm not a doctor and this isn't a diagnosis. What's been bothering you?";

const STAGES: { id: ConsultStage; label: string }[] = [
  { id: "assessment", label: "Symptoms" },
  { id: "details", label: "Details" },
  { id: "medication", label: "Medication" },
  { id: "review", label: "Review" },
];

const URGENCY_STYLES: Record<string, { label: string; className: string }> = {
  emergency: { label: "Call 999 now", className: "bg-destructive/10 text-destructive border-destructive/30" },
  urgent: { label: "Seek urgent care today", className: "bg-amber-500/10 text-amber-700 dark:text-amber-400 border-amber-500/30" },
  routine: { label: "Book a GP appointment", className: "bg-primary-soft text-primary border-primary/30" },
  "self-care": { label: "Monitor at home", className: "bg-success/10 text-success border-success/30" },
};

interface SavedReport {
  id: string;
  title: string;
  created_at: string;
  report: ConsultReport;
}

function reportToText(r: ConsultReport, date: string): string {
  return `DoseAI Consultation Report
${date}

YOUR SYMPTOMS
${r.symptomsSummary}

POSSIBLE EXPLANATIONS (not a diagnosis)
${r.possibleExplanations.map((p) => `• ${p.title}: ${p.explanation}`).join("\n")}

WHAT TO DO NEXT
${r.nextSteps.map((s, i) => `${i + 1}. ${s}`).join("\n")}

WHO TO CONTACT
${r.whoToContact.name} — ${r.whoToContact.why}

WARNING SIGNS — seek urgent help if:
${r.warningSigns.map((w) => `• ${w}`).join("\n")}

---
This report is general health information, not a medical diagnosis. Always consult a qualified healthcare professional.
Generated by DoseAI`;
}

function ConsultationPage() {
  const { user, loading: authLoading } = useAuth();
  const { t } = useTranslation();
  const runTurn = useServerFn(consultationTurn);
  const runReport = useServerFn(consultationReport);

  const [phase, setPhase] = useState<"consent" | "chat" | "report">("consent");
  const [consentChecked, setConsentChecked] = useState(false);
  const [messages, setMessages] = useState<ConsultMessage[]>([]);
  const [input, setInput] = useState("");
  const [typing, setTyping] = useState(false);
  const [quickReplies, setQuickReplies] = useState<string[]>([]);
  const [stage, setStage] = useState<ConsultStage>("assessment");
  const [emergency, setEmergency] = useState(false);
  const [readyForReport, setReadyForReport] = useState(false);
  const [report, setReport] = useState<ConsultReport | null>(null);
  const [reportLoading, setReportLoading] = useState(false);
  const [reportDate, setReportDate] = useState<string>("");
  const [savedReports, setSavedReports] = useState<SavedReport[]>([]);
  const [saving, setSaving] = useState(false);
  const [savedCurrent, setSavedCurrent] = useState(false);

  const scrollRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    if (!user) return;
    supabase
      .from("consultation_reports")
      .select("id, title, created_at, report")
      .order("created_at", { ascending: false })
      .then(({ data }) => {
        if (data) setSavedReports(data as unknown as SavedReport[]);
      });
  }, [user]);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
  }, [messages, typing]);

  useEffect(() => {
    if (phase === "chat" && !typing) inputRef.current?.focus();
  }, [phase, typing]);

  const startConsultation = () => {
    setMessages([{ role: "assistant", content: OPENING_MESSAGE }]);
    setQuickReplies([]);
    setStage("assessment");
    setEmergency(false);
    setReadyForReport(false);
    setReport(null);
    setSavedCurrent(false);
    setPhase("chat");
  };

  const send = async (text: string) => {
    const content = text.trim();
    if (!content || typing) return;
    const nextMessages: ConsultMessage[] = [...messages, { role: "user", content }];
    setMessages(nextMessages);
    setInput("");
    setQuickReplies([]);
    setTyping(true);
    try {
      const turn = await runTurn({ data: { messages: nextMessages } });
      setMessages([...nextMessages, { role: "assistant", content: turn.reply }]);
      setQuickReplies(turn.quickReplies);
      setStage(turn.stage);
      if (turn.emergency) setEmergency(true);
      setReadyForReport(turn.readyForReport);
    } catch (e: any) {
      toast.error(e?.message || "Something went wrong. Please try again.");
    } finally {
      setTyping(false);
    }
  };

  const endConsultation = async () => {
    if (reportLoading || messages.length < 2) return;
    setReportLoading(true);
    try {
      const r = await runReport({ data: { messages } });
      setReport(r);
      setReportDate(
        new Date().toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" })
      );
      setPhase("report");
    } catch (e: any) {
      toast.error(e?.message || "Couldn't create the report. Please try again.");
    } finally {
      setReportLoading(false);
    }
  };

  const copyReport = async () => {
    if (!report) return;
    await navigator.clipboard.writeText(reportToText(report, reportDate));
    toast.success("Report copied to clipboard");
  };

  const downloadReport = () => {
    if (!report) return;
    const blob = new Blob([reportToText(report, reportDate)], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `knowdose-consultation-${new Date().toISOString().slice(0, 10)}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const saveReport = async () => {
    if (!report || !user || saving || savedCurrent) return;
    setSaving(true);
    const title = report.summary.mainComplaint.slice(0, 80) || "Consultation report";
    const { data, error } = await supabase
      .from("consultation_reports")
      .insert({ user_id: user.id, title, report: report as any })
      .select("id, title, created_at, report")
      .single();
    setSaving(false);
    if (error) {
      toast.error("Couldn't save the report. Please try again.");
      return;
    }
    setSavedCurrent(true);
    setSavedReports([data as unknown as SavedReport, ...savedReports]);
    toast.success("Report saved to your account");
  };

  const deleteReport = async (id: string) => {
    const { error } = await supabase.from("consultation_reports").delete().eq("id", id);
    if (error) {
      toast.error("Couldn't delete the report. Please try again.");
      return;
    }
    setSavedReports(savedReports.filter((r) => r.id !== id));
    toast.success("Report deleted");
  };

  const stageIndex = STAGES.findIndex((s) => s.id === stage);

  return (
    <div className="min-h-screen bg-background flex flex-col">
      <SiteHeader />

      <main className="flex-1 max-w-3xl w-full mx-auto px-5 sm:px-8 py-8 flex flex-col">
        {/* Page heading */}
        <div className="flex items-center gap-3 mb-6">
          <div className="w-11 h-11 rounded-2xl bg-[image:var(--gradient-primary)] flex items-center justify-center shadow-[var(--shadow-soft)]">
            <Stethoscope className="w-5 h-5 text-primary-foreground" />
          </div>
          <div>
            <h1 className="font-display text-2xl sm:text-3xl tracking-tight">{t("consult.title")}</h1>
            <p className="text-sm text-muted-foreground">{t("consult.subtitle")}</p>
          </div>
        </div>

        {/* Signed out */}
        {!authLoading && !user && (
          <div className="bg-card rounded-3xl p-10 border border-border/50 shadow-[var(--shadow-card)] text-center">
            <Lock className="w-8 h-8 text-primary mx-auto" />
            <h2 className="mt-4 font-display text-xl">{t("consult.signinTitle")}</h2>
            <p className="mt-2 text-sm text-muted-foreground max-w-md mx-auto">{t("consult.signinSub")}</p>
            <Button asChild className="mt-6 rounded-full bg-[image:var(--gradient-primary)]">
              <Link to="/auth">{t("header.signin")}</Link>
            </Button>
          </div>
        )}

        {/* Consent */}
        {user && phase === "consent" && (
          <div className="space-y-6">
            <div className="bg-card rounded-3xl p-6 sm:p-8 border border-border/50 shadow-[var(--shadow-card)]">
              <h2 className="font-display text-lg">{t("consult.beforeStart")}</h2>
              <ul className="mt-4 space-y-3 text-sm text-muted-foreground">
                {(["consentAI", "consentNotAdvice", "consentPrivacy", "consentEmergency"] as const).map((k) => (
                  <li key={k} className="flex items-start gap-2.5">
                    <ShieldCheck className="w-4 h-4 text-success mt-0.5 shrink-0" />
                    <span>{t(`consult.${k}`)}</span>
                  </li>
                ))}
              </ul>
              <label className="mt-6 flex items-start gap-3 cursor-pointer">
                <Checkbox
                  checked={consentChecked}
                  onCheckedChange={(v) => setConsentChecked(v === true)}
                  className="mt-0.5"
                  aria-label={t("consult.consentBox")}
                />
                <span className="text-sm text-foreground/90">{t("consult.consentBox")}</span>
              </label>
              <Button
                onClick={startConsultation}
                disabled={!consentChecked}
                className="mt-6 w-full sm:w-auto rounded-full bg-[image:var(--gradient-primary)] px-8"
              >
                {t("consult.start")}
                <ChevronRight className="w-4 h-4 ml-1" />
              </Button>
            </div>

            {/* Saved reports */}
            {savedReports.length > 0 && (
              <div className="bg-card rounded-3xl p-6 border border-border/50 shadow-[var(--shadow-card)]">
                <h3 className="font-display text-base flex items-center gap-2">
                  <FileText className="w-4 h-4 text-primary" />
                  {t("consult.savedReports")}
                </h3>
                <ul className="mt-4 space-y-2">
                  {savedReports.map((r) => (
                    <li
                      key={r.id}
                      className="flex items-center gap-3 rounded-2xl border border-border/50 px-4 py-3 hover:border-primary/40 transition-colors"
                    >
                      <button
                        type="button"
                        className="flex-1 text-left min-w-0"
                        onClick={() => {
                          setReport(r.report);
                          setReportDate(
                            new Date(r.created_at).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" })
                          );
                          setSavedCurrent(true);
                          setPhase("report");
                        }}
                      >
                        <p className="text-sm font-medium truncate">{r.title}</p>
                        <p className="text-xs text-muted-foreground">
                          {new Date(r.created_at).toLocaleDateString("en-GB", { dateStyle: "medium" })}
                        </p>
                      </button>
                      <button
                        type="button"
                        onClick={() => deleteReport(r.id)}
                        className="text-muted-foreground hover:text-destructive transition-colors p-1.5"
                        aria-label={t("consult.delete")}
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        )}

        {/* Chat */}
        {user && phase === "chat" && (
          <div className="flex-1 flex flex-col gap-4">
            {/* Progress */}
            <div className="flex items-center gap-1.5 sm:gap-2">
              {STAGES.map((s, i) => (
                <div key={s.id} className="flex-1 flex flex-col gap-1.5">
                  <div
                    className={`h-1.5 rounded-full transition-colors ${
                      i <= stageIndex ? "bg-primary" : "bg-border"
                    }`}
                  />
                  <span
                    className={`text-[10px] sm:text-xs text-center ${
                      i <= stageIndex ? "text-primary font-medium" : "text-muted-foreground"
                    }`}
                  >
                    {s.label}
                  </span>
                </div>
              ))}
            </div>

            {/* Emergency banner */}
            {emergency && (
              <div className="rounded-2xl border border-destructive/40 bg-destructive/10 p-4 flex items-start gap-3">
                <Phone className="w-5 h-5 text-destructive shrink-0 mt-0.5" />
                <div>
                  <p className="font-semibold text-destructive text-sm">{t("consult.emergencyTitle")}</p>
                  <p className="text-sm text-destructive/90 mt-1">{t("consult.emergencyBody")}</p>
                </div>
              </div>
            )}

            {/* Messages */}
            <div
              ref={scrollRef}
              className="flex-1 min-h-[320px] max-h-[55vh] overflow-y-auto bg-card rounded-3xl border border-border/50 shadow-[var(--shadow-card)] p-4 sm:p-6 space-y-4"
            >
              {messages.map((m, i) => (
                <div key={i} className={`flex gap-3 ${m.role === "user" ? "justify-end" : ""}`}>
                  {m.role === "assistant" && (
                    <div className="w-8 h-8 rounded-xl bg-[image:var(--gradient-primary)] flex items-center justify-center shrink-0 mt-0.5">
                      <MessageCircleHeart className="w-4 h-4 text-primary-foreground" />
                    </div>
                  )}
                  <div
                    className={`max-w-[85%] rounded-2xl px-4 py-3 text-sm leading-relaxed whitespace-pre-wrap ${
                      m.role === "user"
                        ? "bg-primary text-primary-foreground rounded-br-md"
                        : "bg-background border border-border/60 rounded-bl-md"
                    }`}
                  >
                    {m.content}
                  </div>
                </div>
              ))}
              {typing && (
                <div className="flex gap-3">
                  <div className="w-8 h-8 rounded-xl bg-[image:var(--gradient-primary)] flex items-center justify-center shrink-0">
                    <MessageCircleHeart className="w-4 h-4 text-primary-foreground" />
                  </div>
                  <div className="bg-background border border-border/60 rounded-2xl rounded-bl-md px-4 py-3 flex gap-1.5 items-center">
                    {[0, 1, 2].map((i) => (
                      <div
                        key={i}
                        className="w-2 h-2 rounded-full bg-primary animate-bounce"
                        style={{ animationDelay: `${i * 150}ms` }}
                      />
                    ))}
                  </div>
                </div>
              )}
            </div>

            {/* Quick replies */}
            {quickReplies.length > 0 && !typing && (
              <div className="flex flex-wrap gap-2">
                {quickReplies.map((q) => (
                  <button
                    key={q}
                    type="button"
                    onClick={() => send(q)}
                    className="px-3.5 py-2 rounded-full bg-card border border-border/60 hover:border-primary/40 hover:bg-primary-soft text-sm transition-colors"
                  >
                    {q}
                  </button>
                ))}
              </div>
            )}

            {/* Input */}
            <div className="bg-card rounded-3xl border border-border/50 shadow-[var(--shadow-card)] p-3 flex items-end gap-2">
              <textarea
                ref={inputRef}
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter" && !e.shiftKey) {
                    e.preventDefault();
                    send(input);
                  }
                }}
                placeholder={t("consult.placeholder")}
                rows={1}
                maxLength={2000}
                className="flex-1 bg-transparent resize-none outline-none text-sm px-3 py-2.5 max-h-32 placeholder:text-muted-foreground/70"
              />
              <Button
                onClick={() => send(input)}
                disabled={!input.trim() || typing}
                size="icon"
                className="rounded-full bg-[image:var(--gradient-primary)] h-10 w-10 shrink-0"
                aria-label={t("consult.send")}
              >
                <Send className="w-4 h-4" />
              </Button>
            </div>

            {/* Actions */}
            <div className="flex flex-wrap items-center justify-between gap-3">
              <button
                type="button"
                onClick={() => setPhase("consent")}
                className="text-sm text-muted-foreground hover:text-foreground inline-flex items-center gap-1.5 transition-colors"
              >
                <RotateCcw className="w-3.5 h-3.5" />
                {t("consult.restart")}
              </button>
              <Button
                onClick={endConsultation}
                disabled={reportLoading || messages.length < 3}
                variant={readyForReport ? "default" : "outline"}
                className={readyForReport ? "rounded-full bg-[image:var(--gradient-primary)]" : "rounded-full"}
              >
                {reportLoading ? (
                  <>
                    <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                    {t("consult.preparingReport")}
                  </>
                ) : (
                  <>
                    <FileText className="w-4 h-4 mr-2" />
                    {t("consult.endAndReport")}
                  </>
                )}
              </Button>
            </div>

            <p className="text-xs text-muted-foreground text-center flex items-center justify-center gap-1.5">
              <ShieldCheck className="w-3.5 h-3.5 text-success" />
              {t("consult.microDisclaimer")}
            </p>
          </div>
        )}

        {/* Report */}
        {user && phase === "report" && report && (
          <div className="space-y-5">
            {report.urgency === "emergency" && (
              <div className="rounded-2xl border border-destructive/40 bg-destructive/10 p-4 flex items-start gap-3">
                <Phone className="w-5 h-5 text-destructive shrink-0 mt-0.5" />
                <div>
                  <p className="font-semibold text-destructive text-sm">{t("consult.emergencyTitle")}</p>
                  <p className="text-sm text-destructive/90 mt-1">{t("consult.emergencyBody")}</p>
                </div>
              </div>
            )}

            <div className="bg-card rounded-3xl border border-border/50 shadow-[var(--shadow-card)] p-6 sm:p-8 space-y-7">
              <div className="flex flex-wrap items-start justify-between gap-3">
                <div>
                  <h2 className="font-display text-xl">{t("consult.reportTitle")}</h2>
                  <p className="text-xs text-muted-foreground mt-1">{reportDate}</p>
                </div>
                <span
                  className={`text-xs font-medium px-3 py-1.5 rounded-full border ${
                    URGENCY_STYLES[report.urgency]?.className ?? URGENCY_STYLES.routine.className
                  }`}
                >
                  {URGENCY_STYLES[report.urgency]?.label ?? report.urgency}
                </span>
              </div>

              <ReportSection title={t("consult.secSymptoms")}>
                <p>{report.symptomsSummary}</p>
              </ReportSection>

              <ReportSection title={t("consult.secExplanations")}>
                <ul className="space-y-3">
                  {report.possibleExplanations.map((p, i) => (
                    <li key={i} className="rounded-2xl bg-background border border-border/50 p-4">
                      <p className="font-medium text-foreground">{p.title}</p>
                      <p className="mt-1">{p.explanation}</p>
                    </li>
                  ))}
                </ul>
              </ReportSection>

              <ReportSection title={t("consult.secNextSteps")}>
                <ol className="space-y-2">
                  {report.nextSteps.map((s, i) => (
                    <li key={i} className="flex items-start gap-2.5">
                      <span className="w-5 h-5 rounded-full bg-primary-soft text-primary text-xs font-semibold flex items-center justify-center shrink-0 mt-0.5">
                        {i + 1}
                      </span>
                      <span>{s}</span>
                    </li>
                  ))}
                </ol>
              </ReportSection>

              <ReportSection title={t("consult.secContact")}>
                <div className="rounded-2xl bg-primary-soft/60 border border-primary/20 p-4">
                  <p className="font-medium text-foreground">{report.whoToContact.name}</p>
                  <p className="mt-1">{report.whoToContact.why}</p>
                </div>
              </ReportSection>

              <ReportSection title={t("consult.secWarning")}>
                <ul className="space-y-2">
                  {report.warningSigns.map((w, i) => (
                    <li key={i} className="flex items-start gap-2.5">
                      <AlertTriangle className="w-4 h-4 text-amber-500 shrink-0 mt-0.5" />
                      <span>{w}</span>
                    </li>
                  ))}
                </ul>
              </ReportSection>

              <div className="rounded-2xl border border-border/60 bg-background px-4 py-3 text-xs text-muted-foreground flex items-start gap-2">
                <ShieldCheck className="w-3.5 h-3.5 mt-0.5 text-success shrink-0" />
                <span>{t("consult.reportDisclaimer")}</span>
              </div>
            </div>

            {/* Report actions */}
            <div className="flex flex-wrap gap-2.5">
              <Button onClick={copyReport} variant="outline" className="rounded-full">
                <Copy className="w-4 h-4 mr-2" />
                {t("consult.copy")}
              </Button>
              <Button onClick={downloadReport} variant="outline" className="rounded-full">
                <Download className="w-4 h-4 mr-2" />
                {t("consult.download")}
              </Button>
              <Button
                onClick={saveReport}
                disabled={saving || savedCurrent}
                className="rounded-full bg-[image:var(--gradient-primary)]"
              >
                {savedCurrent ? (
                  <>
                    <CheckCircle2 className="w-4 h-4 mr-2" />
                    {t("consult.saved")}
                  </>
                ) : (
                  <>
                    <Save className="w-4 h-4 mr-2" />
                    {saving ? t("consult.saving") : t("consult.save")}
                  </>
                )}
              </Button>
              <Button onClick={() => setPhase("consent")} variant="ghost" className="rounded-full ml-auto">
                <RotateCcw className="w-4 h-4 mr-2" />
                {t("consult.newConsultation")}
              </Button>
            </div>
          </div>
        )}
      </main>

      <SiteFooter />
    </div>
  );
}

function ReportSection({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section className="text-sm text-muted-foreground leading-relaxed">
      <h3 className="text-xs font-semibold uppercase tracking-wider text-foreground/70 mb-2.5">{title}</h3>
      {children}
    </section>
  );
}
